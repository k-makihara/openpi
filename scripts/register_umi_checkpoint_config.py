"""Register an inference config for a locally trained dual-arm UMI checkpoint."""

import argparse
import json
import pathlib
import re
import sys


TIMESTAMP_SUFFIX = re.compile(r"_20\d{6}_\d{6}$")


def _parse_named_int(name: str, key: str) -> int | None:
    match = re.search(rf"(?:^|_){re.escape(key)}(\d+)(?:_|$)", name)
    return int(match.group(1)) if match else None


def _infer_config_name(checkpoint_dir: pathlib.Path) -> str:
    if checkpoint_dir.name.isdigit():
        hierarchy_name = checkpoint_dir.parent.parent.name
        if hierarchy_name:
            return hierarchy_name
        return TIMESTAMP_SUFFIX.sub("", checkpoint_dir.parent.name)
    return TIMESTAMP_SUFFIX.sub("", checkpoint_dir.name)


def _load_stats_dimensions(checkpoint_dir: pathlib.Path) -> tuple[str, int, int]:
    stats_paths = sorted((checkpoint_dir / "assets").glob("*/norm_stats.json"))
    if len(stats_paths) != 1:
        raise ValueError(
            f"Expected exactly one assets/*/norm_stats.json, found {len(stats_paths)} in {checkpoint_dir}"
        )

    stats_path = stats_paths[0]
    payload = json.loads(stats_path.read_text(encoding="utf-8"))
    norm_stats = payload.get("norm_stats", payload)
    try:
        state_dim = len(norm_stats["state"]["mean"])
        action_dim = len(norm_stats["actions"]["mean"])
    except (KeyError, TypeError) as exc:
        raise ValueError(f"Unsupported norm stats format: {stats_path}") from exc
    return stats_path.parent.name, state_dim, action_dim


def _infer_history_steps(state_dim: int) -> int:
    # Per history step: (pose9 + gripper1) x 2 arms. Relative state adds pose9 x 2 arms.
    history_numerator = state_dim - 18
    if history_numerator <= 0 or history_numerator % 20 != 0:
        raise ValueError(
            f"State dimension {state_dim} is not a dual-arm relative-state layout (expected 20 * history + 18). "
            "Pass --history-steps only if the checkpoint uses a compatible custom transform."
        )
    return history_numerator // 20


def _render_config(
    *,
    config_name: str,
    asset_id: str,
    repo_id: str,
    history_steps: int,
    action_horizon: int,
    downsample_step: int,
    action_pose_target: str,
    batch_size: int,
) -> str:
    config_name_literal = json.dumps(config_name)
    asset_id_literal = json.dumps(asset_id)
    repo_id_literal = json.dumps(repo_id)
    action_pose_target_literal = json.dumps(action_pose_target)
    return f'''    # Generated by scripts/register_umi_checkpoint_config.py.
    TrainConfig(
        name={config_name_literal},
        model=pi0_config.Pi0Config(
            pi05=True,
            action_horizon={action_horizon},
            action_dim=32,
            discrete_state_input=False,
        ),
        data=LeRobotUmiOriginalDualArmRelativeStateDataConfig(
            repo_id={repo_id_literal},
            assets=AssetsConfig(asset_id={asset_id_literal}),
            base_config=DataConfig(prompt_from_task=True, lerobot_tolerance_s=0.05),
            downsample_step={downsample_step},
            history_steps={history_steps},
            action_horizon_steps={action_horizon},
            action_pose_target={action_pose_target_literal},
        ),
        batch_size={batch_size},
        num_train_steps=30_000,
    ),
'''


def _register_config(config_file: pathlib.Path, config_name: str, config_block: str, dry_run: bool) -> bool:
    source = config_file.read_text(encoding="utf-8")
    if re.search(rf'name\s*=\s*["\']{re.escape(config_name)}["\']', source):
        print(f"Config already registered: {config_name}")
        return False

    marker = "_CONFIGS = [\n"
    if marker not in source:
        raise ValueError(f"Could not find {marker.strip()!r} in {config_file}")
    updated = source.replace(marker, marker + config_block, 1)
    if dry_run:
        print(config_block, end="")
        return False

    tmp_path = config_file.with_suffix(config_file.suffix + ".tmp")
    tmp_path.write_text(updated, encoding="utf-8")
    tmp_path.replace(config_file)
    print(f"Registered config: {config_name}")
    print(f"Updated: {config_file}")
    return True


def main() -> None:
    repo_root = pathlib.Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--checkpoint-dir", required=True, type=pathlib.Path)
    parser.add_argument("--config-name")
    parser.add_argument("--config-file", type=pathlib.Path, default=repo_root / "src/openpi/training/config.py")
    parser.add_argument("--repo-id", help="Original training dataset path or Hugging Face repo ID.")
    parser.add_argument("--source-hz", type=int, default=60)
    parser.add_argument("--effective-hz", type=int)
    parser.add_argument("--history-steps", type=int)
    parser.add_argument("--action-horizon", type=int)
    parser.add_argument("--action-pose-target", choices=("delta", "relative"), default="relative")
    parser.add_argument("--batch-size", type=int)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    checkpoint_dir = args.checkpoint_dir.expanduser().resolve()
    if not (checkpoint_dir / "params").is_dir():
        raise ValueError(f"Checkpoint params directory not found: {checkpoint_dir / 'params'}")

    config_name = args.config_name or _infer_config_name(checkpoint_dir)
    asset_id, state_dim, stats_action_dim = _load_stats_dimensions(checkpoint_dir)
    if stats_action_dim != 20:
        raise ValueError(f"Expected dual-arm UMI action stats dimension 20, got {stats_action_dim}")

    history_steps = args.history_steps or _infer_history_steps(state_dim)
    action_horizon = args.action_horizon or _parse_named_int(config_name, "h")
    effective_hz = args.effective_hz or _parse_named_int(config_name, "hz")
    batch_size = args.batch_size or _parse_named_int(config_name, "bs") or 32
    if action_horizon is None:
        raise ValueError("Could not infer action horizon from the config name; pass --action-horizon")
    if effective_hz is None:
        raise ValueError("Could not infer effective frequency from the config name; pass --effective-hz")
    if effective_hz <= 0 or args.source_hz % effective_hz != 0:
        raise ValueError(
            f"source_hz={args.source_hz} must be evenly divisible by effective_hz={effective_hz}"
        )
    downsample_step = args.source_hz // effective_hz
    repo_id = args.repo_id or asset_id

    print(
        "Resolved:",
        f"name={config_name}",
        f"asset_id={asset_id}",
        f"state_dim={state_dim}",
        f"stats_action_dim={stats_action_dim}",
        f"history_steps={history_steps}",
        f"action_horizon={action_horizon}",
        f"downsample_step={downsample_step}",
        f"action_pose_target={args.action_pose_target}",
        sep="\n  ",
    )
    if args.repo_id is None:
        print("Note: repo_id defaults to asset_id for inference. Pass --repo-id to reuse this config for training.")

    config_block = _render_config(
        config_name=config_name,
        asset_id=asset_id,
        repo_id=repo_id,
        history_steps=history_steps,
        action_horizon=action_horizon,
        downsample_step=downsample_step,
        action_pose_target=args.action_pose_target,
        batch_size=batch_size,
    )
    _register_config(args.config_file.resolve(), config_name, config_block, args.dry_run)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc
